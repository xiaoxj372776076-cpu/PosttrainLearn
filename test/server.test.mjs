import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createApp } from '../server.mjs';

test('local API: complete snapshots, reviews, immutable versions and safe exports', async t => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'legal-lab-test-'));
  const project = fileURLToPath(new URL('../', import.meta.url));
  await fs.cp(path.join(project, 'content'), path.join(temporary, 'content'), { recursive: true, filter: source => source !== path.join(project, 'content/skills') });
  const initial = JSON.parse(await fs.readFile(path.join(project, 'content/skills/index.json'), 'utf8')).versions.find(v => v.version === '1.1.0');
  await fs.mkdir(path.join(temporary, 'content/skills'), { recursive: true });
  await fs.cp(path.join(project, 'content/skills/1.1.0'), path.join(temporary, 'content/skills/1.1.0'), { recursive: true });
  await fs.writeFile(path.join(temporary, 'content/skills/index.json'), JSON.stringify({ versions: [initial] }));
  await fs.cp(path.join(project, 'public'), path.join(temporary, 'public'), { recursive: true });
  for (const directory of ['schemas', 'docs']) await fs.cp(path.join(project, directory), path.join(temporary, directory), { recursive: true });
  const { server } = await createApp({ root: temporary });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await fs.rm(temporary, { recursive: true, force: true }); });
  const url = `http://127.0.0.1:${server.address().port}`;
  const request = async (route, body, headers = {}) => {
    const response = await fetch(url + route, body === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Research-Intent': 'local-edit', ...headers }, body: JSON.stringify(body) });
    return { status: response.status, value: await response.json(), headers: response.headers };
  };
  const bootstrap = await request('/api/bootstrap');
  assert.equal(bootstrap.value.dataset.total, 280);
  assert.equal(bootstrap.value.versions.length, 1);
  assert.equal(bootstrap.value.evaluation.officialLeaderboard.length, 24);
  assert.equal(bootstrap.value.appVersion, '0.4.0');
  assert.equal(bootstrap.value.dossier.normalization, 'partial');
  const dossier = (await request('/api/dossier')).value;
  assert.equal(dossier.schema_version, '0.1'); assert.equal(dossier.case_metadata.training_readiness, 'blocked');
  assert.equal((await request('/api/dossier/schema')).value.schema.title, '诉讼案件全景记录 0.1');
  const exploration = (await request('/api/exploration')).value;
  assert.equal(exploration.stages.length, 12); assert.equal(exploration.seedBank.approved, 0);
  assert.equal(exploration.stages.find(s => s.id === 'questions').status, 'not_run');
  const run=(await request('/api/synthesis/run?id=legal-harbor-001')).value;
  assert.equal(run.config.bon.n,3); assert.equal(run.trainingSamples,0);
  assert.equal(run.stages.length,11); assert.ok(run.warning.includes('隐藏参考答案'));
  const student=run.artifacts['student-files.json'].data;
  assert.ok(!JSON.stringify(student).includes('[p-020]'));
  assert.ok(!JSON.stringify(student).includes('524100'));
  assert.equal((await request('/api/synthesis/run?id=../../.env')).status,404);
  assert.equal((await request('/api/synthesis/artifact?run=legal-harbor-001&file=../../.env')).status,404);
  const runDownload=await fetch(url+'/api/synthesis/artifact?run=legal-harbor-001&file=reference.json');
  assert.equal(runDownload.status,200); assert.ok(runDownload.headers.get('content-disposition').includes('reference.json'));
  const dossierExport = await request('/api/export/dossier');
  assert.deepEqual(dossierExport.value, dossier);
  assert.ok(dossierExport.headers.get('content-disposition').includes('case-dossier-0.1.0.json'));
  const casebookExport = await fetch(url + '/api/export/casebook');
  assert.ok(casebookExport.headers.get('content-disposition').includes('casebook-0.1.0.md'));
  assert.ok((await casebookExport.text()).includes('doc-judgment:p-020'));
  assert.equal((await request('/api/dossier/schema?file=../../server.mjs')).value.schema.$id, 'urn:posttrainlearn:case-dossier:0.1');
  assert.equal((await request('/api/dossier/private-source')).status, 404);
  const listing = await request('/api/records?type=consultation&pageSize=5&page=2');
  assert.equal(listing.value.total, 18); assert.equal(listing.value.records.length, 5);
  assert.equal((await request('/api/records?q=不可能匹配此字符串')).value.total, 0);
  assert.equal((await request('/api/records?page=999')).value.page, 28);
  const record = (await request('/api/records/case-001')).value;
  assert.equal(record.referenceAnswer, null); assert.equal(record.evaluation.models.length, 2);
  assert.equal(record.evaluation.models[1].grade.percentage, 100);
  assert.ok(!JSON.stringify(record).includes('ep-2026'));
  assert.ok(!JSON.stringify(record).includes('reasoningText'));
  const review = { usage: 'candidate', expert: 'expert-01', note: '等待核验', expectedRevision: 0 };
  assert.equal((await request('/api/reviews/case-001', review)).status, 200);
  assert.equal((await request('/api/reviews/case-001', review)).status, 409);
  assert.equal((await request('/api/export/seeds')).value.seeds.length, 0);
  assert.equal((await request('/api/reviews/case-001', { usage: 'holdout', expectedRevision: 1 })).status, 400);
  assert.equal((await request('/api/reviews/case-002', { usage: 'holdout', expectedRevision: 0 })).status, 200);
  assert.equal((await request('/api/reviews/case-002', { usage: 'candidate', expectedRevision: 1 })).status, 400);
  const approved = { usage: 'approved', expert: 'expert-01', note: '归属后适用规则', answer: '审核答案', rationale: '经核验依据', permissionBasis: '测试授权说明', permissionConfirmed: true, answerVerified: true, difficulty: 'D3', patterns: ['amount_classification', 'rule_application'], expectedRevision: 1 };
  assert.equal((await request('/api/reviews/case-001', approved)).status, 200);
  assert.equal((await request('/api/export/seeds')).value.seeds.length, 1);
  const updatedExploration = (await request('/api/exploration')).value;
  assert.equal(updatedExploration.seedBank.approved, 1);
  assert.equal(updatedExploration.seedBank.records[0].id, 'case-001');
  assert.equal(updatedExploration.stages.find(s => s.id === 'seeds').status, 'available');
  assert.equal(updatedExploration.seedBank.selectionLog, null);
  assert.equal((await request('/api/records?usage=approved')).value.total, 1);
  const skill = (await request('/api/skills/1.1.0')).value;
  assert.ok(skill.files.includes('references/few-shot-and-difficulty.md'));
  assert.equal((await request('/api/skills/1.1.0?file=../../server.mjs')).status, 404);
  const version = { version: '1.1.1', parent: '1.1.0', parentFileSha256: skill.fileSha256, file: 'SKILL.md', text: skill.text + '\n测试迭代。\n', note: '验证不可覆盖的版本', author: 'test' };
  assert.equal((await request('/api/skills', version)).status, 201);
  assert.equal((await request('/api/skills', version)).status, 400);
  assert.equal((await request('/api/export/seeds')).value.seeds[0].skill_version, '1.1.0');
  assert.equal((await request('/api/export/seeds')).value.seeds[0].exported_with_skill_version, '1.1.1');
  assert.equal((await request('/api/reviews/case-004', { ...review, skillVersion: '9.9.9' })).status, 404);
  const original = (await request('/api/skills/1.1.0')).value;
  assert.equal(original.text, skill.text);
  assert.ok((await request('/api/skills/1.1.1?file=references/data-contract.md')).value.text.includes('数据契约'));
  const diff = (await request('/api/diff?from=1.1.0&to=1.1.1')).value;
  assert.ok(diff.lines.some(l => l.kind === 'added' && l.text === '测试迭代。'));
  assert.equal((await request('/api/feedback', { skillVersion: '1.1.1', expert: 'test', category: 'difficulty', text: '检查最短解答' })).status, 201);
  const backup = (await request('/api/export/research')).value;
  assert.equal(backup.skillSnapshots.length, 2); assert.equal(backup.state.feedback.length, 1); assert.equal(backup.state.history.length, 5);
  assert.deepEqual(backup.dossier, dossier); assert.equal(backup.pipeline.skill_version, '1.1.0');
  assert.equal(backup.formatVersion,'1.3'); assert.equal(backup.synthesisRuns.length,1);
  assert.equal(backup.hardnessCampaignRounds.length>=1,true);
  assert.equal(backup.synthesisRuns[0].report.training_rows,0);
  assert.equal(backup.synthesisRuns[0].artifacts['stage-P6.json'].data.assessed_difficulty,'D3');
  assert.equal((await request('/api/reviews/case-003', review, { Origin: 'https://evil.example' })).status, 403);
  const caseData = (await request('/api/case')).value;
  assert.ok(!JSON.stringify(caseData.paragraphs).includes('1991年9月27日'));
  assert.ok(!JSON.stringify(caseData.paragraphs).includes('尾号9272'));
  assert.ok(caseData.paragraphs.some(p => p.id === 'p-020' && p.text.includes('52.41万元')));
  assert.equal((await request('/private-source/judgment.raw.html')).status, 404);
  const home = await fetch(url + '/'); assert.equal(home.status, 200); assert.ok((await home.text()).includes('法律数据合成研究学习'));
});
